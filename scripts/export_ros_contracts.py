"""Generate typed commissioning ROS interfaces from canonical Pydantic contracts."""

import json
import typing
from pathlib import Path

from workbench_arm_controller.app import create_app
from workbench_common import ROOT
from workbench_contracts import MicrophoneDevice, MicrophoneResult, MicrophoneTest
from workbench_contracts.ros_transport import (
    controller_bindings,
    field_type,
    message_fields,
    ros_field,
)


def write_changed(path, content):
    if not path.is_file() or path.read_text() != content:
        path.write_text(content)


def main():
    cfg = json.loads((ROOT / "config/development/default.json").read_text())
    cfg["mode"] = "mock"
    cfg["workbench"] = json.loads((ROOT / "config/workbench/default.json").read_text())
    bindings = controller_bindings(create_app(cfg))  # No lifespan or hardware acquisition.
    generated = ROOT / "ros/src/workbench_interfaces/generated"
    generated.mkdir(exist_ok=True)
    models = {}

    def collect(spec):
        if spec.kind == "list":
            collect(spec.child)
        elif spec.kind == "model" and spec.annotation.__name__ not in models:
            models[spec.annotation.__name__] = spec.annotation
            for _, field in message_fields(spec.annotation):
                collect(field)

    for binding in bindings:
        for spec in (*binding["parameters"].values(), binding["result"]):
            collect(spec)
    for model in (MicrophoneDevice, MicrophoneTest, MicrophoneResult):
        collect(field_type(model))
    files = []
    imports = set()

    def annotation_name(annotation):
        if typing.get_origin(annotation) is list:
            return f"list[{annotation_name(typing.get_args(annotation)[0])}]"
        if annotation in (str, bool, int, float):
            return annotation.__name__
        imports.add(annotation.__name__)
        return annotation.__name__

    registry = ["CONTROL_BINDINGS = ["]
    for binding in bindings:
        registry.extend(
            [
                "    {",
                f'        "name": "{binding["name"]}",',
                f'        "method": "{binding["method"]}",',
                f'        "path": "{binding["path"]}",',
                f'        "endpoint": "{binding["endpoint"].__name__}",',
            ]
        )
        if binding["parameters"]:
            registry.append('        "parameters": {')
            for name, spec in binding["parameters"].items():
                registry.append(f'            "{name}": {annotation_name(spec.annotation)},')
            registry.append("        },")
        else:
            registry.append('        "parameters": {},')
        registry.extend(
            [
                f'        "result": {annotation_name(binding["result"].annotation)},',
                "    },",
            ]
        )
    registry.append("]")
    registry_path = ROOT / "packages/contracts/src/workbench_contracts/ros_control.py"
    write_changed(
        registry_path,
        '"""Generated commissioning bindings; run scripts/export_ros_contracts.py."""\n\n'
        + "from . import (\n"
        + "".join(f"    {name},\n" for name in sorted(imports))
        + ")\n\n"
        + "\n".join(registry)
        + "\n",
    )
    for name, model in sorted(models.items()):
        lines = ["# Generated by scripts/export_ros_contracts.py; edit the Python contract."]
        seen = set()
        for field, spec in message_fields(model):
            names = [ros_field(field, spec)]
            if spec.optional:
                names.append("has_" + field)
            if any(name in seen for name in names):
                raise ValueError(f"ROS field collision in {model.__name__}.{field}")
            seen.update(names)
            if spec.optional:
                lines.append(f"bool has_{field}")
            lines.append(f"{spec.ros_type} {ros_field(field, spec)}")
        filename = f"msg/Api{name}.msg"
        write_changed(generated.parent / filename, "\n".join(lines) + "\n")
        files.append(filename)
    for binding in bindings:
        lines = [
            "# Generated commissioning service; request and result domains must match.",
            "string domain",
        ]
        for name, spec in binding["parameters"].items():
            lines.append(f"{spec.ros_type} {ros_field(name, spec)}")
        lines.extend(
            [
                "---",
                "string domain",
                "bool success",
                "int32 error_status",
                "string error_message",
                f"{binding['result'].ros_type} value",
            ]
        )
        filename = f"srv/{binding['name']}.srv"
        write_changed(generated.parent / filename, "\n".join(lines) + "\n")
        files.append(filename)
    write_changed(
        generated / "interfaces.cmake",
        "# Generated by scripts/export_ros_contracts.py\nset(WORKBENCH_CONTROL_INTERFACES\n"
        + "".join(f'  "{name}"\n' for name in sorted(files))
        + ")\n",
    )
    expected = {Path(file).name for file in files}
    for path in generated.iterdir():
        if path.name != "interfaces.cmake":
            raise ValueError(f"Unexpected generated file requires review: {path}")
    for pattern in ("msg/Api*.msg", "srv/Control*.srv"):
        for path in generated.parent.glob(pattern):
            if path.name not in expected:
                raise ValueError(f"Stale generated file requires review: {path}")
    print(f"Generated {len(models)} messages and {len(bindings)} commissioning services")


if __name__ == "__main__":
    main()
